-- Ручное решение по движению, которое автоматика не должна переигрывать.
--
-- 7–8 октября 2026 в «Запросили отчисление» разом перевели 41 старую сделку. Сверка с
-- выгрузкой платформы globalos.kz показала: ни один из этих людей в октябре не уходил —
-- 40 были отчислены или выпущены ещё до 16 сентября, четверо до сих пор учатся.
-- Правила по стадиям Битрикса такой случай не ловят: стадия говорит, где карточка лежала,
-- а не учился ли человек на самом деле.
--
-- null — решает автоматика (обычный режим). true/false — решение проставлено руками
-- после сверки, и пересчёт его не трогает.
alter table student_moves add column if not exists manual_counted boolean;

comment on column student_moves.manual_counted is
  'Ручное решение по сверке с выгрузкой платформы: null — считает автоматика, true/false — зафиксировано руками';
